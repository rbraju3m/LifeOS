<?php

namespace App\Modules\Tasks\Models;

use App\Modules\Shared\Models\BaseModel;
use App\Modules\Spaces\Contracts\SpaceOwnedContent;
use App\Modules\Spaces\Enums\Visibility;
use App\Modules\Spaces\Models\Concerns\BelongsToSpace;
use App\Modules\Tags\Contracts\TagSummary;
use App\Modules\Tasks\Enums\TaskStatus;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;

/**
 * A task (docs/blueprint/10 §10.4). due_date is the local due date; due_at
 * is the UTC instant when a time is set (then due_date is its local date in
 * `timezone`). due_sort is generated by the database.
 *
 * @property string $id
 * @property string $space_id
 * @property string|null $created_by
 * @property Visibility $visibility
 * @property string|null $task_list_id
 * @property string|null $assignee_user_id
 * @property string $title
 * @property string|null $description
 * @property TaskStatus $status
 * @property int $priority
 * @property Carbon|null $due_date
 * @property Carbon|null $due_at
 * @property string $timezone
 * @property string|null $rrule
 * @property string|null $recurrence_series_id
 * @property Carbon|null $completed_at
 * @property string|null $completed_by
 * @property int $sort_order
 * @property Carbon $created_at
 * @property Carbon $updated_at
 * @property Carbon|null $deleted_at
 */
class Task extends BaseModel implements SpaceOwnedContent
{
    use BelongsToSpace, SoftDeletes;

    /**
     * Filled by TaskTags::load() for API responses; not a database column.
     *
     * @var list<TagSummary>|null
     */
    public ?array $tagSummaries = null;

    /**
     * Ownership, status, due fields and completion are set by actions only.
     *
     * @var list<string>
     */
    protected $fillable = ['title', 'description', 'priority', 'sort_order'];

    /** @var array<string, mixed> */
    protected $attributes = [
        'visibility' => 'space',
        'status' => 'open',
        'priority' => 0,
        'sort_order' => 0,
        'description' => null,
        'task_list_id' => null,
        'assignee_user_id' => null,
        'due_date' => null,
        'due_at' => null,
        'rrule' => null,
        'recurrence_series_id' => null,
        'completed_at' => null,
        'completed_by' => null,
        'deleted_at' => null,
    ];

    public static function contentType(): string
    {
        return 'task';
    }

    protected function casts(): array
    {
        return [
            'status' => TaskStatus::class,
            'priority' => 'integer',
            'sort_order' => 'integer',
            'due_date' => 'date',
            'due_at' => 'datetime',
            'completed_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<TaskList, $this>
     */
    public function list(): BelongsTo
    {
        return $this->belongsTo(TaskList::class, 'task_list_id');
    }

    /**
     * Tag IDs from this module's own pivot table.
     *
     * @return list<string>
     */
    public function tagIds(): array
    {
        /** @var list<string> $ids */
        $ids = DB::table('task_tag')->where('task_id', $this->id)->pluck('tag_id')->all();

        return $ids;
    }

    /**
     * @param  list<string>  $tagIds  already checked to be in this task's space
     */
    public function syncTagIds(array $tagIds): void
    {
        DB::table('task_tag')->where('task_id', $this->id)->delete();
        DB::table('task_tag')->insert(array_map(
            fn (string $tagId) => ['task_id' => $this->id, 'tag_id' => $tagId],
            array_values(array_unique($tagIds)),
        ));
    }
}
